"""``donkey scaffold``: candidate declaration tables for the services a static
scan finds, built offline and deterministically (#1747, milestone 28).

:func:`build_scaffold` scans the code with
:func:`~donkey_kit.registry.scan.scan`, so it never imports or runs it, and
proposes the ``.donkey-kit.toml`` tables the project file does not have yet:

* ``[donkey.agents.<name>]`` for each ``@donkey.agent`` and
  ``[donkey.mcp_servers.<id>]`` for each server a ``@donkey.tool`` names
  (how each is reached, #1193, #1260);
* ``[donkey.publication]`` and one ``[donkey.publication.assets.<id>]`` per
  service (its Exchange coordinates, #218);
* with ``expose=True``, ``[donkey.expose]`` and one
  ``[donkey.expose.services.<id>]`` per service the gateway can front (#226).

What the code says is written as an active key. What it cannot say (an
endpoint, a protocol, a version, a gateway) is a deployment fact, so it is a
commented placeholder (``# protocol = "<a2a_v1 or other>"``): a scaffold
never invents a fact, and a commented key declares nothing.

The input is the code and the committed project ``.donkey-kit.toml`` alone.
Neither the developer's ``.donkey-kit.local.toml``, the user-wide config nor
the environment is read, so two checkouts of one commit give the same bytes.
A table the project file already has is left alone, even when it is only
partly filled in: it is listed in :attr:`Scaffold.declared`, not proposed.

:meth:`Scaffold.apply` turns the candidates into the project file's next text
(#1748). It only appends: the authored text is kept byte for byte, comments
and all, and the whole tables are added after it. The result is parsed back
and must hold exactly the old tables plus the new ones, or
:class:`ScaffoldRefused` is raised and nothing is to be written. An inline
table or a dotted key that a header cannot extend is refused that way rather
than rewritten. Writing the file is the CLI's job.
"""

from __future__ import annotations

import copy
import json
import sys
from collections import Counter
from collections.abc import Collection
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from ..core.config import TOML_NAME
from ..core.toml_text import basic_string, comment, key
from .readiness import Readiness, assess
from .scan import ScanIssue, ScanResult, scan

if sys.version_info >= (3, 11):
    import tomllib
else:  # 3.10 has no stdlib tomllib; the [core] dep ``tomli`` backfills it.
    import tomli as tomllib

__all__ = [
    "SCAFFOLD_FORMAT",
    "CandidateTable",
    "Placeholder",
    "Scaffold",
    "ScaffoldRefused",
    "UnknownService",
    "build_scaffold",
]

#: The version of the scaffold's JSON document, bumped when its shape changes
#: incompatibly, as ``scan_format`` and ``plan_format`` are.
SCAFFOLD_FORMAT = 1

_HEADER = (
    "# Generated by `donkey scaffold` from a static scan: no code was imported or run.",
    "# Commented keys are deployment facts the code does not say: replace each",
    "# <placeholder> with the real value, then uncomment the line.",
)


class UnknownService(ValueError):
    """A service ID asked for is not one the scan found; the message lists those it did."""


class ScaffoldRefused(ValueError):
    """The candidates cannot be appended to the project file without changing
    what it already declares. The message names the table, never file content."""


@dataclass(frozen=True)
class Placeholder:
    """A key the scaffold cannot fill in: ``hint`` says what belongs there."""

    key: str
    hint: str


@dataclass(frozen=True)
class CandidateTable:
    """One table the project file lacks.

    ``table`` is its key path (``("donkey", "agents", "support-triage")``);
    ``service_id`` is ``None`` for the shared ``[donkey.publication]`` and
    ``[donkey.expose]`` tables. ``kind`` is ``agent``, ``mcp_server``,
    ``publication``, ``publication_asset``, ``expose`` or ``expose_service``.
    ``values`` are its active keys, ``unresolved`` its commented placeholders
    and ``notes`` the comments above it (where in the code it comes from).
    """

    table: tuple[str, ...]
    service_id: str | None
    kind: str
    values: dict[str, str] = field(default_factory=dict)
    unresolved: tuple[Placeholder, ...] = ()
    notes: tuple[str, ...] = ()

    @property
    def name(self) -> str:
        """The table's header text, ``donkey.agents.support-triage``."""
        return ".".join(key(part) for part in self.table)

    def to_toml(self) -> str:
        """The table as TOML: its notes, header, active keys and placeholders."""
        lines = [f"# {comment(note)}" for note in self.notes]
        lines.append(f"[{self.name}]")
        lines += [f"{key(k)} = {basic_string(v)}" for k, v in self.values.items()]
        lines += [f"# {key(p.key)} = {basic_string(f'<{p.hint}>')}" for p in self.unresolved]
        return "\n".join(lines) + "\n"

    def to_dict(self) -> dict[str, Any]:
        """The table as plain JSON-ready data."""
        return {
            "table": self.name,
            "path": list(self.table),
            "service_id": self.service_id,
            "kind": self.kind,
            "values": dict(self.values),
            "unresolved": [{"key": p.key, "hint": p.hint} for p in self.unresolved],
            "notes": list(self.notes),
        }


@dataclass(frozen=True)
class Scaffold:
    """What ``donkey scaffold`` proposes for one scanned root.

    ``destination`` is the project file the candidates belong in, relative to
    the root. ``declared`` names the service tables the project file already
    has, and ``unattributed`` the tools with no ``server=`` (which belong to
    no table until one is set, #503). ``issues`` are the scan's plus the
    scaffold's own: ``scaffold-conflict`` when a key the candidate needs is
    already something other than a table, and ``scaffold-refused`` when the
    CLI declined to write. ``written`` says whether the candidates were
    written to ``destination``; a preview never writes. ``readiness`` is what
    each workflow still needs (#1749), assessed offline from the committed
    project file. The candidates add no value a planner reads (an
    ``asset_id`` equal to the service ID is its default), so it holds after
    they are written as before.
    """

    candidates: tuple[CandidateTable, ...] = ()
    declared: tuple[str, ...] = ()
    unattributed: tuple[str, ...] = ()
    issues: tuple[ScanIssue, ...] = ()
    destination: str = TOML_NAME
    written: bool = False
    readiness: Readiness = field(default_factory=lambda: Readiness(scan_valid=True))

    @property
    def unresolved(self) -> int:
        """How many placeholders the candidates leave to fill in."""
        return sum(len(c.unresolved) for c in self.candidates)

    def to_toml(self) -> str:
        """The candidates as one TOML document, or ``""`` when there are none."""
        if not self.candidates:
            return ""
        return "\n".join(["\n".join(_HEADER) + "\n", *(c.to_toml() for c in self.candidates)])

    def to_dict(self) -> dict[str, Any]:
        """The scaffold as plain JSON-ready data, the TOML preview included."""
        return {
            "scaffold_format": SCAFFOLD_FORMAT,
            "destination": self.destination,
            "candidates": [c.to_dict() for c in self.candidates],
            "declared": list(self.declared),
            "unattributed": list(self.unattributed),
            "unresolved": self.unresolved,
            "issues": [i.to_dict() for i in self.issues],
            "toml": self.to_toml(),
            "written": self.written,
            "readiness": self.readiness.to_dict(),
        }

    def to_json(self) -> str:
        """Canonical JSON: sorted keys, two-space indent, trailing newline."""
        return json.dumps(self.to_dict(), sort_keys=True, indent=2) + "\n"

    def apply(self, existing: str | None) -> str:
        """The project file's text with the candidates appended.

        ``existing`` is the file's current text, or ``None`` when there is no
        file, in which case the result is :meth:`to_toml`. Otherwise it is
        ``existing`` unchanged followed by the candidate tables, in the file's
        own line ending. With no candidates, ``existing`` comes back as is.

        Raises:
            ScaffoldRefused: ``existing`` is not valid TOML, or the appended
                tables would not parse, or would change a value it already
                declares (an inline table or a dotted key in the way).
        """
        if existing is None:
            return self.to_toml()
        if not self.candidates:
            return existing
        try:
            before = tomllib.loads(existing)
        except tomllib.TOMLDecodeError as exc:
            raise ScaffoldRefused(f"{self.destination} is not valid TOML ({exc})") from exc
        newline = "\r\n" if "\r\n" in existing else "\n"
        addition = self.to_toml().replace("\n", newline)
        if existing and not existing.endswith("\n"):
            existing += newline
        text = existing + (newline if existing else "") + addition
        try:
            after = tomllib.loads(text)
        except tomllib.TOMLDecodeError as exc:
            raise ScaffoldRefused(
                f"appending to {self.destination} would not be valid TOML ({exc}); an inline "
                "table or dotted key is in the way, so add the tables from "
                "`donkey scaffold --dry-run` by hand"
            ) from exc
        expected = copy.deepcopy(before)
        for candidate in self.candidates:
            node = expected
            for part in candidate.table:
                node = node.setdefault(part, {})
            node.update(candidate.values)
        if after != expected:
            raise ScaffoldRefused(
                f"appending to {self.destination} would change what it already declares; "
                "add the tables from `donkey scaffold --dry-run` by hand"
            )
        return text


def build_scaffold(
    root: str | Path, *, expose: bool = False, services: Collection[str] | None = None
) -> Scaffold:
    """Propose the declaration tables ``root``'s project file lacks, offline,
    and assess what each workflow still needs (#1749).

    ``root`` is a directory or one ``.py`` file, as for
    :func:`~donkey_kit.registry.scan.scan`. ``expose`` adds the
    ``[donkey.expose]`` tables. ``services`` limits the proposals and the
    exposure readiness to those service IDs; the shared tables and publication
    readiness stay project-wide. Reads no environment variable, user file or
    local overlay, and makes no network call.

    Raises:
        FileNotFoundError: ``root`` does not exist.
        UnknownService: a name in ``services`` is no scanned service's ID.
    """
    base = Path(root)
    result = scan(base, local_overlay=False)
    if services is not None:
        found = sorted({a.name for a in result.agents} | {s.id for s in result.mcp_servers})
        unknown = sorted(set(services) - set(found))
        if unknown:
            raise UnknownService(
                f"no agent or MCP server has service ID {', '.join(map(repr, unknown))}; "
                f"found {', '.join(found) or 'none'}"
            )
    directory = base.parent if base.is_file() else base
    project = _project(directory / TOML_NAME)
    builder = _Builder(project)
    if project is not None:
        _propose(builder, result, expose=expose, services=services)
    issues = sorted(
        (*result.issues, *builder.issues), key=lambda i: (i.path, i.line, i.kind, i.subject)
    )
    return Scaffold(
        candidates=tuple(builder.candidates),
        declared=tuple(builder.declared),
        unattributed=tuple(t.qualname for t in result.unattributed),
        issues=tuple(issues),
        readiness=assess(result, base, project, services=services),
    )


def _project(path: Path) -> dict[str, Any] | None:
    """The project file's tables: ``{}`` when it is absent, ``None`` when it
    cannot be read or parsed (the scan reports that, and nothing is proposed:
    what it holds is unknown)."""
    if not path.is_file():
        return {}
    try:
        data: dict[str, Any] = tomllib.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, tomllib.TOMLDecodeError):
        return None
    return data


def _propose(
    builder: _Builder, result: ScanResult, *, expose: bool, services: Collection[str] | None
) -> None:
    # A repeated service ID is a scan issue; proposing a table for it would
    # pick one of the services at random.
    ids = Counter([a.name for a in result.agents] + [s.id for s in result.mcp_servers])

    def wanted(sid: str) -> bool:
        return ids[sid] == 1 and (services is None or sid in services)

    agents = sorted((a for a in result.agents if wanted(a.name)), key=lambda a: a.name)
    servers = [s for s in result.mcp_servers if wanted(s.id)]  # sorted by the scan

    for a in agents:
        builder.add(
            ("donkey", "agents", a.name),
            a.name,
            "agent",
            unresolved=(
                Placeholder("protocol", "a2a_v1 or other"),
                Placeholder("endpoint", "the URL the agent is served at; required for a2a_v1"),
            ),
            notes=(f"agent {a.qualname}, {a.path}:{a.line}",),
        )
    for s in servers:
        builder.add(
            ("donkey", "mcp_servers", s.id),
            s.id,
            "mcp_server",
            unresolved=(
                Placeholder("transport", "stdio, streamable-http or sse"),
                Placeholder("endpoint", "the server's http or https URL; none for stdio"),
            ),
            notes=(f"MCP server with tools: {', '.join(s.tools)}",),
        )

    services = sorted([a.name for a in agents] + [s.id for s in servers])
    if not services:
        return
    builder.add(
        ("donkey", "publication"),
        None,
        "publication",
        unresolved=(
            Placeholder("version", "a semantic version, such as 1.0.0"),
            Placeholder("group_id", "the Exchange group; the configured org_id when unset"),
        ),
        notes=("Exchange coordinates for `donkey publish`",),
    )
    for sid in services:
        builder.add(
            ("donkey", "publication", "assets", sid),
            sid,
            "publication_asset",
            values={"asset_id": sid},
        )

    if not expose:
        return
    # The gateway fronts MCP servers and A2A agents (expose_plan); an agent's
    # protocol is what the project file declares, unknown until it does.
    exposable = sorted([s.id for s in servers] + [a.name for a in agents if a.protocol == "a2a_v1"])
    if not exposable:
        return
    builder.add(
        ("donkey", "expose"),
        None,
        "expose",
        unresolved=(Placeholder("target", "the name of the gateway to deploy to"),),
        notes=("the gateway `donkey expose` deploys to",),
    )
    for sid in exposable:
        builder.add(
            ("donkey", "expose", "services", sid),
            sid,
            "expose_service",
            unresolved=(
                Placeholder(
                    "upstream", "the URL the gateway reaches it on; its endpoint by default"
                ),
            ),
        )


class _Builder:
    """Collects candidates for the tables ``project`` does not have."""

    def __init__(self, project: dict[str, Any] | None) -> None:
        self.project = project or {}
        self.candidates: list[CandidateTable] = []
        self.declared: list[str] = []
        self.issues: list[ScanIssue] = []

    def add(
        self,
        table: tuple[str, ...],
        service_id: str | None,
        kind: str,
        *,
        values: dict[str, str] | None = None,
        unresolved: tuple[Placeholder, ...] = (),
        notes: tuple[str, ...] = (),
    ) -> None:
        candidate = CandidateTable(table, service_id, kind, values or {}, unresolved, notes)
        node: object = self.project
        for depth in range(len(table) + 1):
            if not isinstance(node, dict):
                where = ".".join(key(p) for p in table[:depth])
                self.issues.append(
                    ScanIssue(
                        "scaffold-conflict",
                        candidate.name,
                        TOML_NAME,
                        0,
                        f"{where} in {TOML_NAME} is not a table, so [{candidate.name}] "
                        "cannot be scaffolded; make it a table or remove it",
                    )
                )
                return
            if depth == len(table):
                break
            if table[depth] not in node:
                self.candidates.append(candidate)
                return
            node = node[table[depth]]
        if service_id is not None:
            self.declared.append(candidate.name)
