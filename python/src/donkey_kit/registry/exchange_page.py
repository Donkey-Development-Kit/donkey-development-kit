"""The Exchange page ``donkey publish`` writes for an MCP asset (#1269).

:func:`documentation_page` renders it as Markdown from the plan and the scan:
the asset's name and description, the ``documentation`` file it declares, its
tools with their parameters, how it is reached, and where it was published
from. Exchange shows the page as the asset's Home page, and Agent Fabric as the
Documentation section of its Overview (docs/verified-apis.md §12.3).

Exchange renders headings one level down and shows inline code in a table cell
with its backticks, so table cells are plain text. The page never carries a
credential, an org ID or a pre-signed URL: the group ID is left out of the
coordinates it shows.
"""

from __future__ import annotations

from dataclasses import dataclass

from .publish_plan import PlannedAsset
from .scan import ScanResult

__all__ = ["PageSource", "documentation_page"]


@dataclass(frozen=True)
class PageSource:
    """Where a publish ran from, for the page's provenance; every field is
    optional. :func:`donkey_kit.cli.publish` fills it from the GitHub Actions
    environment."""

    repository_url: str | None = None
    commit: str | None = None
    ref: str | None = None
    run_url: str | None = None


def documentation_page(
    asset: PlannedAsset, result: ScanResult, *, source: PageSource | None = None
) -> str:
    """The Markdown page for the ``mcp`` asset ``asset``, scanned as ``result``."""
    lines = [f"# {asset.name}", ""]
    if asset.description:
        lines += [asset.description.strip(), ""]
    if asset.documentation_text and asset.documentation_text.strip():
        lines += [asset.documentation_text.strip(), ""]

    tools = sorted((t for t in result.tools if t.server == asset.service_id), key=lambda t: t.name)
    lines += ["## Tools", ""]
    if not tools:
        lines += ["This server declares no tools.", ""]
    for tool in tools:
        lines += [f"### {tool.name}", ""]
        if tool.description:
            lines += [tool.description.strip(), ""]
        if tool.parameters:
            lines += ["| Parameter | Type |", "| --- | --- |"]
            lines += [
                f"| {_cell(p.name)} | {_cell(p.annotation or 'any')} |" for p in tool.parameters
            ]
            lines.append("")
        else:
            lines += ["No parameters.", ""]

    server = next(s for s in result.mcp_servers if s.id == asset.service_id)
    lines += ["## Connecting", "", f"- **Transport:** {server.transport or 'streamable-http'}"]
    if asset.endpoint:
        lines.append(f"- **Endpoint:** <{asset.endpoint}>")
    if asset.protocol_version:
        lines.append(f"- **MCP protocol version:** {asset.protocol_version}")
    lines.append("")

    lines += ["## Provenance", "", f"- **Asset:** {asset.asset_id} {asset.version}"]
    if source and source.repository_url:
        lines.append(f"- **Repository:** <{source.repository_url}>")
    if source and source.commit:
        commit = source.commit[:12]
        if source.repository_url:
            commit = f"[{commit}]({source.repository_url}/commit/{source.commit})"
        lines.append(f"- **Commit:** {commit}" + (f" on {source.ref}" if source.ref else ""))
    if source and source.run_url:
        lines.append(f"- **Published by:** [this CI run]({source.run_url})")
    lines += [f"- **Content digest:** {asset.digest}", ""]
    lines.append("_Generated by `donkey publish` from the server's code._")
    return "\n".join(lines) + "\n"


def _cell(text: str) -> str:
    """``text`` as one Markdown table cell: one line, pipes escaped."""
    return " ".join(text.split()).replace("|", "\\|")
